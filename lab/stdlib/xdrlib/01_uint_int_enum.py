import xdrlib

p = xdrlib.Packer()
p.pack_uint(0)
p.pack_uint(1)
p.pack_uint(4294967295)
p.pack_int(-1)
p.pack_int(-2147483648)
p.pack_int(2147483647)
p.pack_enum(2)
p.pack_uint(42)
print(p.get_buffer().hex())

u = xdrlib.Unpacker(p.get_buffer())
print(u.unpack_uint())
print(u.unpack_uint())
print(u.unpack_uint())
print(u.unpack_int())
print(u.unpack_int())
print(u.unpack_int())
print(u.unpack_enum())
print(u.unpack_uint())
u.done()
print(u.get_position(), len(u.get_buffer()))
