#!/usr/bin/env python3
"""Differential runner for the plain-Python typed-path fuzz lab.

    python3 lab/fuzzpy/run.py --start 0 --count 2000 --out lab/fuzzpy/out --jobs 2

Every seed is generated by gen.py, run under CPython and built with the default AIL build
(`ail_chatgpt.py compile --syntax python`, no AIL_UNIFIED_FORCE and no AIL_IR).  stdout, the last
line of stderr and the exit status are compared.  Each process gets a 1.5 GB address-space limit
and a 10 s run timeout.  Classes: same / refused / overflow / DIFF / crash / timeout / skipped.
"""
import argparse
import json
import os
import resource
import shutil
import subprocess
import sys
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen  # noqa: E402

CAP = 1 << 20
LIMIT_AS = 1500000 * 1024


def limit():
    resource.setrlimit(resource.RLIMIT_AS, (LIMIT_AS, LIMIT_AS))


def run_proc(cmd, timeout, env=None, cwd=None):
    try:
        r = subprocess.run(cmd, capture_output=True, timeout=timeout, env=env, cwd=cwd,
                           preexec_fn=limit)
        return r.returncode, r.stdout, r.stderr, False
    except subprocess.TimeoutExpired as e:
        return None, e.stdout or b'', e.stderr or b'', True


def text(b):
    return b[:CAP].decode('utf-8', 'replace')


def last_line(b):
    lines = [l for l in text(b).strip().splitlines() if l.strip()]
    return lines[-1] if lines else ''


def first_diff(a, b):
    al, bl = a.splitlines(), b.splitlines()
    for i in range(max(len(al), len(bl))):
        x = al[i] if i < len(al) else '<end>'
        y = bl[i] if i < len(bl) else '<end>'
        if x != y:
            return 'line %d: cpython=%r ail=%r' % (i + 1, x[:100], y[:100])
    return 'no line difference'


def classify(cpy, ail):
    c_rc, c_out, c_err, _ = cpy
    a_rc, a_out, a_err, a_to = ail
    if a_to:
        return 'timeout', 'run timed out'
    if a_rc is not None and (a_rc < 0 or a_rc >= 128):
        return 'crash', 'binary died with status %d' % a_rc
    c_last, a_last = last_line(c_err), last_line(a_err)
    if a_rc == c_rc and a_out == c_out and a_last == c_last:
        return 'same', ''
    low = a_err.lower()
    if (a_rc != 0 and (b'overflow' in low or b'int64' in low or b'limit:' in low)
            and c_out.startswith(a_out)):
        return 'overflow', 'AIL int64 stop (CPython rc=%s): %s' % (c_rc, a_last[:150])
    if (a_out == c_out and a_rc == c_rc and a_last
            and c_last.endswith(a_last) and c_last != a_last):
        return 'DIFF', 'stderr-only: cpython last=%r ail last=%r' % (c_last[:100], a_last[:100])
    bits = []
    if a_rc != c_rc:
        bits.append('exit cpython=%s ail=%s' % (c_rc, a_rc))
    if a_out != c_out:
        bits.append(first_diff(text(c_out), text(a_out)))
    if a_last != c_last:
        bits.append('stderr last cpython=%r ail=%r' % (c_last[:100], a_last[:100]))
    return 'DIFF', '; '.join(bits)


LOCK = threading.Lock()


def one_seed(seed, args, modes):
    src = gen.generate(seed, [f for f in args.off.split(',') if f])
    work = Path(args.out) / 'work' / str(seed)
    work.mkdir(parents=True, exist_ok=True)
    py = work / 'prog.py'
    py.write_text(src, encoding='utf-8')
    ail_src = work / 'prog.ail'
    ail_src.write_text(src, encoding='utf-8')
    env = dict(os.environ, PYTHONIOENCODING='utf-8', PYTHONHASHSEED='0')
    for key in ('AIL_IR', 'AIL_UNIFIED_FORCE', 'AIL_STRICT'):
        env.pop(key, None)
    cpy = run_proc([sys.executable, str(py)], args.timeout, env=env)
    results = []
    if cpy[3] or len(cpy[1]) > CAP:
        results.append({'seed': seed, 'cls': 'skipped', 'reason': 'cpython timeout or oversized output'})
        shutil.rmtree(work, ignore_errors=True)
        return results
    exe = work / 'exe'
    t0 = time.time()
    crc, cout, cerr, cto = run_proc(
        [sys.executable, '-B', str(args.ail), 'compile', str(ail_src), '--syntax', 'python', '-o', str(exe)],
        args.compile_timeout, env=env)
    rec = {'seed': seed, 'cpython_rc': cpy[0], 'ms': 0}
    msg = text(cerr or cout)
    rec['fallback'] = 'built on the general path' in msg
    if cto:
        rec.update(cls='timeout', reason='compiler timed out')
        ail = None
    elif crc == 3:
        lines = [l for l in msg.strip().splitlines() if l.strip()]
        detail = (lines[-1] if lines else '')[:200]
        low = msg.lower()
        if 'int64' in low or 'overflow' in low or 'does not fit' in low:
            rec.update(cls='overflow', reason='compile-time int64 stop: ' + detail)
        else:
            rec.update(cls='refused', reason=detail)
        ail = None
    elif crc != 0:
        lines = [l for l in msg.strip().splitlines() if l.strip()]
        detail = lines[-1][:200] if lines else ''
        low = msg.lower()
        if 'int64' in low or 'overflow' in low or 'does not fit' in low:
            rec.update(cls='overflow', reason='compile-time int64 stop: ' + detail)
        elif 'not in the subset' in low or 'write instead' in low or crc == 2:
            rec.update(cls='refused', reason='compiler rc=%s: %s' % (crc, detail))
        else:
            rec.update(cls='crash', reason=('compiler rc=%s: ' % crc) + detail)
        ail = None
    else:
        ail = run_proc([str(exe)], args.timeout, env=env)
        rec['ail_rc'] = ail[0]
        rec['cls'], rec['reason'] = classify(cpy, ail)
        rec['stdout_diff'] = cpy[1] != ail[1]
        rec['stderr_diff'] = cpy[2] != ail[2]
        rec['first_diff'] = first_diff(text(cpy[1]), text(ail[1])) if rec['stdout_diff'] else ''
    rec['path'] = 'general' if rec.get('fallback') else 'typed'
    rec['ms'] = int((time.time() - t0) * 1000)
    if rec['cls'] in ('DIFF', 'crash', 'timeout'):
        d = Path(args.out) / 'findings' / ('seed%d-%s' % (seed, rec['cls']))
        d.mkdir(parents=True, exist_ok=True)
        (d / 'prog.py').write_text(src, encoding='utf-8')
        (d / 'cpython.stdout').write_text(text(cpy[1]), encoding='utf-8')
        (d / 'cpython.stderr').write_text(text(cpy[2]), encoding='utf-8')
        if ail:
            (d / 'ail.stdout').write_text(text(ail[1]), encoding='utf-8')
            (d / 'ail.stderr').write_text(text(ail[2]), encoding='utf-8')
        else:
            (d / 'compile.stderr').write_text(msg, encoding='utf-8')
        (d / 'info.json').write_text(json.dumps(rec, indent=1), encoding='utf-8')
    results.append(rec)
    with LOCK:
        with open(Path(args.out) / 'results.jsonl', 'a', encoding='utf-8') as fh:
            for r in results:
                fh.write(json.dumps(r) + '\n')
    shutil.rmtree(work, ignore_errors=True)
    return results


CLASSES = ('silent', 'loud-ok', 'crash', 'refused', 'other')


def summary_class(r):
    cls = r.get('cls')
    if cls == 'refused':
        return 'refused'
    if cls == 'overflow':
        return 'loud-ok'
    if cls == 'crash':
        return 'crash'
    if cls == 'DIFF':
        if (r.get('cpython_rc') == 0 and r.get('ail_rc') == 0
                and r.get('stdout_diff') and not r.get('reason', '').startswith('stderr-only')):
            return 'silent'
        return 'other'
    return 'other'


def summary_rows(records):
    rows = []
    for r in sorted(records, key=lambda r: r['seed']):
        first = r.get('first_diff') or ''
        if not first and r.get('cls') in ('DIFF', 'refused', 'overflow', 'crash', 'timeout'):
            first = r.get('reason', '').splitlines()[0] if r.get('reason') else ''
        rows.append({'seed': r['seed'], 'class': summary_class(r),
                     'path': r.get('path', 'typed'), 'first_diff': first})
    return rows


def write_summary_json(records, path):
    p = Path(path)
    merged = {}
    if p.exists():
        try:
            for row in json.loads(p.read_text(encoding='utf-8')):
                merged[row['seed']] = row
        except (ValueError, TypeError, KeyError):
            merged = {}
    for row in summary_rows(records):
        merged[row['seed']] = row
    rows = [merged[k] for k in sorted(merged)]
    p.write_text(json.dumps(rows, indent=0) + '\n', encoding='utf-8')
    return rows


def summarize(records, args, elapsed):
    names = ['same', 'refused', 'overflow', 'DIFF', 'crash', 'timeout', 'skipped']
    done = len({r['seed'] for r in records})
    built = [r for r in records if r.get('cls') not in ('refused', 'skipped', 'timeout')]
    typed = [r for r in built if not r.get('fallback')]
    lines = ['## fuzzpy: seeds %d..%d (%d run)' % (args.start, args.start + args.count - 1, done), '',
             '| class | count |', '|---|---|']
    for c in names:
        lines.append('| %s | %d |' % (c, sum(1 for r in records if r['cls'] == c)))
    diffs = [r for r in records if r['cls'] == 'DIFF']
    silent = [r for r in diffs if not r.get('reason', '').startswith('stderr-only')]
    lines += ['', 'DIFF: %d (silent stdout/exit: %d; stderr-only: %d)' % (
        len(diffs), len(silent), len(diffs) - len(silent)), '',
        'built: %d; typed path: %d (%.1f%%); general path: %d' % (
        len(built), len(typed), 100.0 * len(typed) / len(built) if built else 0,
        len(built) - len(typed)), '', 'Elapsed %.0f s.' % elapsed, '']
    bad = [r for r in records if r['cls'] in ('DIFF', 'crash')]
    if bad:
        lines += ['### Findings', '']
        for r in sorted(bad, key=lambda r: r['seed']):
            lines.append('- seed %d [%s] %s' % (r['seed'], r['cls'], r['reason'][:220]))
        lines.append('')
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--start', type=int, default=0)
    ap.add_argument('--count', type=int, default=2000)
    ap.add_argument('--out', default=str(HERE / 'out'))
    ap.add_argument('--jobs', type=int, default=2)
    ap.add_argument('--off', default='')
    ap.add_argument('--timeout', type=float, default=10)
    ap.add_argument('--compile-timeout', type=float, default=120)
    ap.add_argument('--budget', type=float, default=0)
    ap.add_argument('--ail', default=str(HERE.parent.parent / 'AIL_CURRENT' / 'ail_chatgpt.py'))
    ap.add_argument('--summary-json', default=str(HERE / 'summary.json'))
    args = ap.parse_args()
    out = Path(args.out)
    (out / 'findings').mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    (out / 'results.jsonl').write_text('', encoding='utf-8')
    records = []
    futures = []
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        for seed in range(args.start, args.start + args.count):
            if args.budget and time.time() - t0 > args.budget:
                break
            futures.append(pool.submit(one_seed, seed, args, ['default']))
        for i, f in enumerate(futures):
            records.extend(f.result())
            if (i + 1) % 100 == 0:
                print('%d/%d in %.0f s' % (i + 1, len(futures), time.time() - t0), flush=True)
    (out / 'summary.md').write_text(summarize(records, args, time.time() - t0), encoding='utf-8')
    write_summary_json(records, args.summary_json)
    print((out / 'summary.md').read_text(encoding='utf-8'))


if __name__ == '__main__':
    main()
