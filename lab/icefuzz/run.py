#!/usr/bin/env python3
"""Build seeded mutants, classify compiler results, minimize crash reproducers.

    python3 lab/icefuzz/run.py --seed 0 --count 2000 --jobs 2

Every mutant is generated by mutate.py (already checked to parse and exit 0
under CPython 3.12 within 5 s), compiled with the default AIL build under a
1.5 GB address-space limit and a 60 s limit, then run and compared with CPython.
Classes: built-and-matching, built-and-different (a silent difference when both
CPython and AIL exit 0 and the stdout differs), refused-by-name, internal-error.
Internal errors are grouped by the last traceback frame; one minimised
reproducer per group is written to lab/icefuzz/crashes/.  Silent differences
are minimised the same way and filed first.
"""
import argparse
import ast
import json
import os
import re
import resource
import shutil
import subprocess
import sys
import threading
import time
from concurrent.futures import ThreadPoolExecutor, wait, FIRST_COMPLETED
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import mutate  # noqa: E402

LIMIT_AS = 1500000 * 1024
CAP = 1 << 20
FRAME_RE = re.compile(r'File "([^"]+)", line (\d+), in ([^\n]+)')


def limit():
    resource.setrlimit(resource.RLIMIT_AS, (LIMIT_AS, LIMIT_AS))


def run_proc(cmd, timeout, env=None, cwd=None):
    try:
        r = subprocess.run(cmd, stdin=subprocess.DEVNULL, capture_output=True,
                           timeout=timeout, env=env, cwd=cwd, preexec_fn=limit)
        return r.returncode, r.stdout, r.stderr, False
    except subprocess.TimeoutExpired as e:
        return None, e.stdout or b'', e.stderr or b'', True
    except OSError as e:
        return 127, b'', str(e).encode(), False


def text(b):
    return (b or b'')[:CAP].decode('utf-8', 'replace')


def default_env():
    env = dict(os.environ, PYTHONIOENCODING='utf-8', PYTHONHASHSEED='0')
    for key in ('AIL_IR', 'AIL_UNIFIED_FORCE', 'AIL_STRICT'):
        env.pop(key, None)
    return env


def first_diff(a, b):
    al, bl = a.splitlines(), b.splitlines()
    for i in range(max(len(al), len(bl))):
        x = al[i] if i < len(al) else '<end>'
        y = bl[i] if i < len(bl) else '<end>'
        if x != y:
            return 'line %d: cpython=%r ail=%r' % (i + 1, x[:120], y[:120])
    return 'no line difference'


def detail_line(msg):
    lines = [l.strip() for l in msg.strip().splitlines() if l.strip()]
    for l in lines:
        low = l.lower()
        if ('not in the subset' in low or 'int64' in low or 'out of range' in low
                or 'refus' in low):
            return l[:240]
    return (lines[-1] if lines else '')[:240]


def traceback_group(msg, rc):
    frames = FRAME_RE.findall(msg)
    if frames:
        path, line, func = frames[-1]
        func = func.strip()
        key = 'traceback:' + (func if func and func != '<module>'
                              else '%s:%s' % (Path(path).name, line))
        head = 'File "%s", line %s, in %s' % (path, line, frames[-1][2].strip())
        return key, head
    if 'Traceback (most recent call last):' in msg:
        lines = [l for l in msg.splitlines() if l.strip()]
        key = 'traceback:' + (lines[-1][:120] if lines else 'unknown')
        return key, (lines[-1] if lines else 'Traceback')[:300]
    errs = [l.strip() for l in msg.splitlines() if 'error:' in l.lower()]
    if errs:
        line = re.sub(r'^.*?(\w[\w.-]*\.[ch]):\d+:\d+:\s*', r'\1: ', errs[0])
        return 'c-compiler:' + line[:160], errs[0][:300]
    lines = [l for l in msg.splitlines() if l.strip()]
    return 'exit-%s' % rc, (lines[-1] if lines else 'exit %s' % rc)[:300]


def compile_source(source, work, timeout=60.0, env=None):
    work = Path(work)
    work.mkdir(parents=True, exist_ok=True)
    src = work / 'prog.py'
    exe = work / 'prog.bin'
    src.write_text(source, encoding='utf-8')
    if exe.exists():
        exe.unlink()
    crc, cout, cerr, cto = run_proc(
        [sys.executable, '-B', str(ROOT / 'AIL_CURRENT' / 'ail_chatgpt.py'),
         'compile', str(src), '--syntax', 'python', '-o', str(exe)],
        timeout, env=env, cwd=work)
    return crc, cout, cerr, cto, exe, src


def classify_compiler(crc, cout, cerr, cto):
    msg = text(cerr) + text(cout)
    if cto:
        return 'internal', 'timeout>60s', 'compile timed out after 60 s', msg
    if crc == 0:
        return 'built', '', '', msg
    if crc in (2, 3):
        return 'refused', '', detail_line(msg), msg
    key, head = traceback_group(msg, crc)
    return 'internal', key, head, msg


class Runner:
    def __init__(self, args):
        self.args = args
        self.out = Path(args.out)
        self.findings = self.out / 'findings'
        self.stop = threading.Event()
        self.lock = threading.Lock()

    def one(self, seed):
        if self.stop.is_set():
            return None
        src, ops, corpus = mutate.generate(seed, detail=True)
        rec = {'seed': seed, 'mutations': ops, 'corpus': corpus,
               'cls': 'discarded', 'reason': ''}
        if src is None:
            rec['reason'] = 'no CPython-valid mutant'
            return rec
        work = self.out / 'work' / str(seed)
        shutil.rmtree(work, ignore_errors=True)
        work.mkdir(parents=True, exist_ok=True)
        prog = work / 'prog.py'
        prog.write_text(src, encoding='utf-8')
        env = default_env()
        t0 = time.time()
        cpy = run_proc([sys.executable, '-B', str(prog)], 5.0, env=env, cwd=work)
        if cpy[3]:
            rec.update(cls='discarded', reason='cpython timeout after generation')
            shutil.rmtree(work, ignore_errors=True)
            return rec
        if cpy[0] != 0:
            rec.update(cls='discarded', reason='cpython exited %s after generation' % cpy[0])
            shutil.rmtree(work, ignore_errors=True)
            return rec
        crc, cout, cerr, cto, exe, _ = compile_source(src, work, self.args.compile_timeout, env)
        kind, group, head, msg = classify_compiler(crc, cout, cerr, cto)
        rec.update(cpython_rc=cpy[0], compile_rc=crc)
        if kind == 'built':
            ail = run_proc([str(exe)], self.args.timeout, env=env, cwd=work)
            rec['ail_rc'] = ail[0]
            if ail[3]:
                rec.update(cls='internal', group='runtime-timeout>10s',
                           head='compiled program timed out after 10 s')
            elif ail[1] == cpy[1] and ail[0] == cpy[0]:
                rec['cls'] = 'matching'
            else:
                last = (text(ail[2]).strip().splitlines() or [''])[-1]
                loud = ail[0] != 0
                silent = (not loud and cpy[0] == 0 and ail[1] != cpy[1])
                rec.update(cls='different', ail_rc=ail[0],
                           stdout_diff=ail[1] != cpy[1], loud=loud, silent=silent,
                           reason=('loud runtime stop: ' + last[:180]) if loud
                           else first_diff(text(cpy[1]), text(ail[1]))
                           if ail[1] != cpy[1]
                           else 'exit cpython=%s ail=%s' % (cpy[0], ail[0]))
                if silent:
                    self.stop.set()
        elif kind == 'refused':
            rec.update(cls='refused', reason=head)
        else:
            rec.update(cls='internal', group=group, head=head, reason=head)
        rec['ms'] = int((time.time() - t0) * 1000)
        if rec['cls'] in ('internal', 'different'):
            d = self.findings / ('seed%d' % seed)
            d.mkdir(parents=True, exist_ok=True)
            (d / 'prog.py').write_text(src, encoding='utf-8')
            (d / 'cpython.stdout').write_text(text(cpy[1]), encoding='utf-8')
            (d / 'cpython.stderr').write_text(text(cpy[2]), encoding='utf-8')
            (d / 'compile.stdout').write_text(text(cout), encoding='utf-8')
            (d / 'compile.stderr').write_text(text(cerr), encoding='utf-8')
            if rec['cls'] == 'different':
                (d / 'ail.stdout').write_text(text(ail[1]), encoding='utf-8')
                (d / 'ail.stderr').write_text(text(ail[2]), encoding='utf-8')
            (d / 'info.json').write_text(json.dumps(rec, indent=1), encoding='utf-8')
            rec['dir'] = str(d)
        shutil.rmtree(work, ignore_errors=True)
        return rec


def _same_crash(source, wanted, work, env, args):
    crc, cout, cerr, cto, exe, _ = compile_source(source, work, args.compile_timeout, env)
    kind, group, head, msg = classify_compiler(crc, cout, cerr, cto)
    return kind == 'internal' and group == wanted, head, msg


def minimize(source, wanted, args, work):
    """Delete statements while the compiler keeps failing in the same group."""
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return source, '', 0
    attempts = [0]
    deadline = time.time() + args.min_time

    def lists_of(root):
        out = []
        for node in ast.walk(root):
            for field, value in ast.iter_fields(node):
                if (isinstance(value, list) and value
                        and all(isinstance(x, ast.stmt) for x in value)):
                    out.append(value)
        return out

    def attempt(root):
        if attempts[0] >= args.min_attempts or time.time() > deadline:
            return None
        try:
            ast.fix_missing_locations(root)
            cand = ast.unparse(root)
            ast.parse(cand)
        except (ValueError, SyntaxError, RecursionError):
            return None
        d = Path(work) / ('try%d' % attempts[0])
        attempts[0] += 1
        ok, head, msg = _same_crash(cand, wanted, d, default_env(), args)
        if ok:
            return cand, head, msg
        return None

    best = source
    best_head, best_msg = None, ''
    changed = True
    while changed and attempts[0] < args.min_attempts and time.time() < deadline:
        changed = False
        for body in lists_of(tree):
            i = len(body) - 1
            while i >= 0 and attempts[0] < args.min_attempts and time.time() < deadline:
                stmt = body.pop(i)
                got = attempt(tree)
                if got is None:
                    body.insert(i, stmt)
                else:
                    best, best_head, best_msg = got
                    changed = True
                i -= 1
    if best_head is None:
        ok, head, msg = _same_crash(best, wanted, Path(work) / 'base', default_env(), args)
        best_head, best_msg = head, msg
    return best, best_head or '', best_msg or '', attempts[0]


def _statement_lists(root):
    out = []
    for node in ast.walk(root):
        for field, value in ast.iter_fields(node):
            if (isinstance(value, list) and value
                    and all(isinstance(x, ast.stmt) for x in value)):
                out.append(value)
    return out


def _still_silent(source, work, env, args):
    """True when CPython and AIL both exit 0 but their stdout differs."""
    work = Path(work)
    work.mkdir(parents=True, exist_ok=True)
    prog = work / 'prog.py'
    prog.write_text(source, encoding='utf-8')
    cpy = run_proc([sys.executable, '-B', str(prog)], 5.0, env=env, cwd=work)
    if cpy[3] or cpy[0] != 0:
        return False
    crc, cout, cerr, cto, exe, _ = compile_source(source, work, args.compile_timeout, env)
    if cto or crc != 0:
        return False
    ail = run_proc([str(exe)], args.timeout, env=env, cwd=work)
    return not ail[3] and ail[0] == 0 and ail[1] != cpy[1]


def minimize_silent(source, args, work):
    """Delete statements while CPython and AIL keep exiting 0 with different output."""
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return source, 0
    attempts = [0]
    deadline = time.time() + args.min_time

    def attempt(root):
        if attempts[0] >= args.min_attempts or time.time() > deadline:
            return None
        try:
            ast.fix_missing_locations(root)
            cand = ast.unparse(root)
            ast.parse(cand)
        except (ValueError, SyntaxError, RecursionError):
            return None
        d = Path(work) / ('try%d' % attempts[0])
        attempts[0] += 1
        return cand if _still_silent(cand, d, default_env(), args) else None

    best = source
    changed = True
    while changed and attempts[0] < args.min_attempts and time.time() < deadline:
        changed = False
        for body in _statement_lists(tree):
            i = len(body) - 1
            while i >= 0 and attempts[0] < args.min_attempts and time.time() < deadline:
                stmt = body.pop(i)
                got = attempt(tree)
                if got is None:
                    body.insert(i, stmt)
                else:
                    best = got
                    changed = True
                i -= 1
    return best, attempts[0]


def slug(s):
    s = re.sub(r'[^A-Za-z0-9_.-]+', '-', s).strip('-')
    return s[:70] or 'crash'


def silent_descriptor(source):
    """A short stable name for a minimised silent difference."""
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return 'difference'
    parts = []
    for n in ast.walk(tree):
        if (isinstance(n, ast.Name) and isinstance(n.ctx, ast.Store)
                and n.id in mutate.BUILTIN_NAMES):
            parts.append(n.id.lower())
            break
    if any(isinstance(n, ast.Global) for n in ast.walk(tree)):
        parts.append('global')
    return slug('-'.join(parts)) or 'difference'


def write_results(records, args, minimised, elapsed):
    internal = [r for r in records if r.get('cls') == 'internal']
    different = [r for r in records if r.get('cls') == 'different']
    silent = [r for r in different if r.get('silent')]
    groups = {}
    for r in internal:
        groups.setdefault(r.get('group') or 'unknown', []).append(r)
    lines = ['# icefuzz: compiler crash fuzzing', '',
             'Command: `python3 lab/icefuzz/run.py --seed %d --count %d --jobs %d '
             '--out %s --budget %g`'
             % (args.seed, args.count, args.jobs, args.out, args.budget), '',
             'Corpus: a fast subset of `lab/stdlib/*/*.py` (<=%d lines, files importing `re`/`decimal`/`datetime`/`tomllib` omitted; '
             'regex/decimal/datetime and other high-lowering modules omitted so each mutant fits the 60 s budget), '
             '`lab/compare/src/*/main.py` (<=%d lines), `lab/limits/*.py` (<=%d lines). '
             'Each seed mutates one program; every mutant parses and exits 0 '
             'in CPython 3.12 within 5 s (candidates CPython rejects are discarded).'
             % (mutate.MAX_STDLIB_LINES, mutate.MAX_COMPARE_LINES, mutate.MAX_LIMIT_LINES), '',
             '| class | count |', '|---|---|']
    for cls, label in (('matching', 'built and matching'),
                       ('different', 'built and different'),
                       ('refused', 'refused by name'),
                       ('internal', 'internal error'),
                       ('discarded', 'discarded (no valid mutant)')):
        lines.append('| %s | %d |' % (label, sum(1 for r in records if r.get('cls') == cls)))
    lines += ['| **classified** | **%d** |' % len(records), '',
              'Internal errors per 2000 mutants: **%.1f** (observed %d in %d). '
              'Elapsed %.0f s.' % (2000.0 * len(internal) / len(records) if records else 0,
                                   len(internal), len(records), elapsed), '']
    if silent:
        lines += ['**The run stopped at the first silent difference (seed %d)**, after '
                  '%d mutants. The remaining seeds were not run.'
                  % (min(r['seed'] for r in silent), len(records)), '']

    lines += ['## Silent differences (built, stdout differs)', '']
    if silent:
        lines += ['These stop the run; they are listed before crashes as the job requires. '
                  'A silent difference is a build where CPython exits 0 and AIL exits 0 '
                  'but the stdout differs.', '',
                  '| seed | corpus mutation | first difference | reproducer |', '|---|---|---|---|']
        for r in sorted(silent, key=lambda r: r['seed']):
            rep = '`crashes/%s`' % r['reproducer'] if r.get('reproducer') else ''
            lines.append('| %d | %s | %s | %s |'
                         % (r['seed'], ', '.join(r.get('mutations', [])),
                            r.get('reason', '').replace('|', '\\|')[:300], rep))
        first = sorted(silent, key=lambda r: r['seed'])[0]
        if first.get('reproducer'):
            fname = first['reproducer']
            lines += ['', 'Reproducer (`lab/icefuzz/crashes/%s`, seed %d):'
                      % (fname, first['seed']), '', '```python',
                      first.get('silent_source', '').rstrip(), '```', '', '```sh',
                      'ulimit -v 1500000',
                      'python3 -B AIL_CURRENT/ail_chatgpt.py compile '
                      'lab/icefuzz/crashes/%s --syntax python -o /tmp/%s.bin'
                      % (fname, Path(fname).stem), '```', '']
    else:
        lines.append('None.')
    lines.append('')

    other = [r for r in different if r not in silent]
    if other:
        lines += ['## Built and different (loud stop or exit status)', '',
                  '| seed | mutations | reason |', '|---|---|---|']
        for r in sorted(other, key=lambda r: r['seed']):
            lines.append('| %d | %s | %s |' % (r['seed'], ', '.join(r.get('mutations', [])),
                                               r.get('reason', '').replace('|', '\\|')[:300]))
        lines.append('')
        if any(not r.get('stdout_diff') for r in other):
            lines += ['Rows whose stdout matches CPython but whose exit status differs are '
                      'real oracle differences (CPython 3.12 compares stdout and exit status); '
                      'they are not invalid comparisons.', '']

    lines += ['## Internal errors grouped by the last traceback frame', '']
    if groups:
        lines += ['| group | count | seeds | reproducer |', '|---|---|---|---|']
        for group in sorted(groups, key=lambda g: (-len(groups[g]), g)):
            rs = groups[group]
            seeds = ', '.join(str(r['seed']) for r in sorted(rs, key=lambda r: r['seed'])[:10])
            if len(rs) > 10:
                seeds += ', ...'
            rep = ''
            if group in minimised:
                rep = '`crashes/%s`' % minimised[group]['file']
            lines.append('| `%s` | %d | %s | %s |'
                         % (group.replace('|', '\\|')[:160], len(rs), seeds, rep))
        lines.append('')
        lines += ['## Minimised reproducers', '']
        for group in sorted(groups, key=lambda g: (-len(groups[g]), g)):
            m = minimised.get(group)
            if not m:
                continue
            lines += ['### `%s`' % group, '',
                      'File: `lab/icefuzz/crashes/%s` (%d lines, %d compile probes).'
                      % (m['file'], len(m['source'].splitlines()), m.get('attempts', 0)), '',
                      '```sh',
                      'ulimit -v 1500000',
                      'python3 -B AIL_CURRENT/ail_chatgpt.py compile '
                      'lab/icefuzz/crashes/%s --syntax python -o /tmp/%s.bin'
                      % (m['file'], Path(m['file']).stem),
                      '```', '',
                      'Traceback head:', '', '```',
                      m['head'].strip()[:1200], '```', '']
    else:
        lines.append('None.')
        lines.append('')

    reasons = {}
    for r in records:
        if r.get('cls') == 'refused':
            key = (r.get('reason') or '').split(':')[-1].strip()[:110]
            reasons[key] = reasons.get(key, 0) + 1
    if reasons:
        lines += ['## Top refusal reasons', '']
        for k, v in sorted(reasons.items(), key=lambda kv: -kv[1])[:10]:
            lines.append('- %d x %s' % (v, k))
        lines.append('')
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--seed', type=int, default=0)
    ap.add_argument('--count', type=int, default=2000)
    ap.add_argument('--jobs', type=int, default=2)
    ap.add_argument('--out', default=str(HERE / 'out'))
    ap.add_argument('--results', default=str(HERE / 'RESULTS.md'))
    ap.add_argument('--crashes', default=str(HERE / 'crashes'))
    ap.add_argument('--timeout', type=float, default=10.0)
    ap.add_argument('--compile-timeout', type=float, default=60.0)
    ap.add_argument('--budget', type=float, default=3300.0,
                    help='stop starting new mutants after this many seconds (0 = no limit)')
    ap.add_argument('--min-attempts', type=int, default=45)
    ap.add_argument('--min-time', type=float, default=90.0)
    ap.add_argument('--no-minimise', action='store_true')
    args = ap.parse_args()
    out = Path(args.out)
    shutil.rmtree(out, ignore_errors=True)
    (out / 'findings').mkdir(parents=True, exist_ok=True)
    crashes = Path(args.crashes)
    crashes.mkdir(parents=True, exist_ok=True)
    for old in crashes.glob('*.py'):
        old.unlink()

    runner = Runner(args)
    records = []
    t0 = time.time()
    seeds = list(range(args.seed, args.seed + args.count))
    next_i = 0
    pending = set()
    with ThreadPoolExecutor(max_workers=max(1, args.jobs)) as ex, \
            open(out / 'results.jsonl', 'w', encoding='utf-8') as jl:
        def submit():
            nonlocal next_i
            while (next_i < len(seeds) and not runner.stop.is_set()
                   and len(pending) < max(2, args.jobs * 2)):
                if args.budget and time.time() - t0 > args.budget:
                    next_i = len(seeds)
                    break
                pending.add(ex.submit(runner.one, seeds[next_i]))
                next_i += 1
        submit()
        done = 0
        while pending:
            finished, pending = wait(pending, return_when=FIRST_COMPLETED)
            for fut in finished:
                rec = fut.result()
                done += 1
                if rec is not None:
                    records.append(rec)
                    jl.write(json.dumps(rec) + '\n')
                    jl.flush()
                if done % 100 == 0:
                    print('%d/%d in %.0f s' % (done, len(seeds), time.time() - t0),
                          flush=True)
            submit()

    minimised = {}
    if not args.no_minimise:
        groups = {}
        for r in records:
            if r.get('cls') == 'internal' and r.get('dir'):
                groups.setdefault(r['group'], []).append(r)
        order = sorted(groups, key=lambda g: (-len(groups[g]), g))
        for n, group in enumerate(order, 1):
            rs = groups[group]
            rep = min(rs, key=lambda r: len((Path(r['dir']) / 'prog.py').read_text(
                encoding='utf-8').splitlines()))
            source = (Path(rep['dir']) / 'prog.py').read_text(encoding='utf-8')
            work = out / 'minimise' / ('g%02d' % n)
            src, head, msg, attempts = minimize(source, group, args, work)
            fname = 'crash-%02d-%s.py' % (n, slug(group))
            (crashes / fname).write_text(src, encoding='utf-8')
            minimised[group] = {'file': fname, 'source': src, 'head': head,
                               'attempts': attempts, 'seed': rep['seed']}
            print('minimised %s -> %s (%d lines)' % (group, fname, len(src.splitlines())),
                  flush=True)

    for n, r in enumerate(sorted((r for r in records
                                  if r.get('cls') == 'different' and r.get('silent')),
                                 key=lambda r: r['seed']), 1):
        source = (Path(r['dir']) / 'prog.py').read_text(encoding='utf-8')
        if args.no_minimise:
            src, attempts = source, 0
        else:
            work = out / 'minimise' / ('s%02d' % n)
            src, attempts = minimize_silent(source, args, work)
        fname = 'silent-%02d-%s.py' % (n, silent_descriptor(source))
        (crashes / fname).write_text(src, encoding='utf-8')
        r['reproducer'] = fname
        r['silent_source'] = src
        r['silent_attempts'] = attempts
        print('minimised silent seed %d -> %s (%d lines)'
              % (r['seed'], fname, len(src.splitlines())), flush=True)

    elapsed = time.time() - t0
    md = write_results(records, args, minimised, elapsed)
    Path(args.results).write_text(md, encoding='utf-8')
    print(md)
