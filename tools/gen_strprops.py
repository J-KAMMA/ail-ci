"""Generate the STRPRED runtime section (full Unicode str.isalpha()/isalnum()/isdigit()/isdecimal()/
isnumeric()/isspace()/isupper()/islower()/istitle()) into cruntime.py.

    python3 tools/gen_strprops.py

Everything is derived from the running CPython (3.12: Unicode 15.0) by asking its own single-character
predicates, so the result is CPython's. One byte of flags per code point, in a two-level table
(block index + deduplicated blocks):

  bit 0  c.isalpha()          bit 4  blocks isupper():  not ("A" + c).isupper()   (c is lowercase or titlecase)
  bit 1  c.isdecimal()        bit 5  blocks islower():  not ("a" + c).islower()   (c is uppercase or titlecase)
  bit 2  c.isdigit()          bit 6  c.isupper()  (cased and upper, when not blocked)
  bit 3  c.isnumeric()        bit 7  c.islower()  (cased and lower, when not blocked)

CPython's isupper() is "no lowercase/titlecase character and at least one uppercase one", islower() the
mirror image, and istitle() is a small state machine over (uppercase-or-titlecase, lowercase, other)
classes; bits 4-7 are exactly those classes (bit 5 is the uppercase-or-titlecase class istitle() needs,
bit 7 its lowercase class). isspace() needs no table: it is the 29 code points ail__is_ws already holds,
checked against the running CPython here. isalnum() is any of bits 0-3, checked against c.isalnum().
The section is written between the BEGIN/END GENERATED STRPRED markers in cruntime.py.
"""
import sys
import unicodedata
from pathlib import Path

CRUNTIME = Path(__file__).resolve().parents[1] / 'AIL_CURRENT/python/pkg-v12/cruntime.py'
BEGIN, END = '# BEGIN GENERATED STRPRED\n', '# END GENERATED STRPRED\n'
WS = [0x09, 0x0A, 0x0B, 0x0C, 0x0D] + list(range(0x1C, 0x21)) + [0x85, 0xA0, 0x1680] + \
    list(range(0x2000, 0x200B)) + [0x2028, 0x2029, 0x202F, 0x205F, 0x3000]


def flags(cp):
    c = chr(cp)
    f = 0
    if c.isalpha():
        f |= 1
    if c.isdecimal():
        f |= 2
    if c.isdigit():
        f |= 4
    if c.isnumeric():
        f |= 8
    if not ('A' + c).isupper():
        f |= 16
    if not ('a' + c).islower():
        f |= 32
    if c.isupper():
        f |= 64
    if c.islower():
        f |= 128
    assert c.isalnum() == bool(f & 15), hex(cp)
    return f


def build(shift):
    size = 1 << shift
    values = [0 if 0xD800 <= cp <= 0xDFFF else flags(cp) for cp in range(0x110000)]
    limit = max(cp for cp, v in enumerate(values) if v) + 1
    nblocks = (limit + size - 1) // size
    blocks, index, seen = [], [], {}
    for b in range(nblocks):
        chunk = tuple(values[b * size:(b + 1) * size] + [0] * max(0, size - len(values[b * size:(b + 1) * size])))
        if chunk not in seen:
            seen[chunk] = len(blocks)
            blocks.append(chunk)
        index.append(seen[chunk])
    wide = len(blocks) > 255
    total = len(index) * (2 if wide else 1) + len(blocks) * size
    return total, shift, index, blocks, wide, limit


def main():
    assert sorted(c for c in range(0x110000) if chr(c).isspace()) == sorted(WS), 'whitespace set changed'
    total, shift, index, blocks, wide, limit = min(build(s) for s in range(3, 9))
    flat = [v for blk in blocks for v in blk]
    lines = lambda items, per: '\n'.join('    ' + ', '.join(str(x) for x in items[i:i + per]) + ','
                                         for i in range(0, len(items), per))
    section = r'''/* Full Unicode str.isalpha()/isalnum()/isdigit()/isdecimal()/isnumeric()/isspace()/isupper()/
   islower()/istitle(), generated by tools/gen_strprops.py from CPython @PY@ (Unicode @UNI@) -- do not
   edit by hand. One flag byte per code point in a two-level table (@BLOCKS@ distinct blocks of @SIZE@, @TOTAL@ bytes).
   Bits: 1 alpha, 2 decimal, 4 digit, 8 numeric, 16 blocks isupper(), 32 blocks islower() (= the
   uppercase-or-titlecase class istitle() needs), 64 upper, 128 lower. Every function is false for "". */
static const @ITYPE@ ail__sp_idx[@NIDX@] = {
@IDX@
};
static const uint8_t ail__sp_blk[@NBLK@] = {
@BLK@
};
static inline unsigned ail__sp(uint32_t c) {
    uint32_t b = c >> @SHIFT@;
    return b < @NIDX@u ? ail__sp_blk[((uint32_t)ail__sp_idx[b] << @SHIFT@) | (c & @MASK@u)] : 0u;
}
/* Walk the code points of s; stop with 0 as soon as one lacks every bit of `mask`. ASCII is a
   plain byte step. */
static int64_t ail__str_all(ail_str s, unsigned mask) {
    if (s.n == 0) return 0;
    for (int64_t i = 0; i < s.n; ) {
        uint32_t c = s.p[i];
        if (c < 0x80) i++; else { c = ail_str_point(s, i); i = ail_str_next_unit(s, i); }
        if (!(ail__sp(c) & mask)) return 0;
    }
    return 1;
}
static int64_t ail_str_isalpha(ail_str s) { return ail__str_all(s, 1u); }
static int64_t ail_str_isdecimal(ail_str s) { return ail__str_all(s, 2u); }
static int64_t ail_str_isdigit(ail_str s) { return ail__str_all(s, 4u); }
static int64_t ail_str_isnumeric(ail_str s) { return ail__str_all(s, 8u); }
static int64_t ail_str_isalnum(ail_str s) { return ail__str_all(s, 15u); }
static int64_t ail_str_isspace(ail_str s) {
    if (s.n == 0) return 0;
    for (int64_t i = 0; i < s.n; ) {
        uint32_t c = s.p[i];
        if (c < 0x80) i++; else { c = ail_str_point(s, i); i = ail_str_next_unit(s, i); }
        if (!ail__is_ws(c)) return 0;
    }
    return 1;
}
/* isupper(): no lowercase/titlecase character, at least one uppercase one. */
static int64_t ail_str_isupper(ail_str s) {
    int cased = 0;
    for (int64_t i = 0; i < s.n; ) {
        uint32_t c = s.p[i];
        if (c < 0x80) i++; else { c = ail_str_point(s, i); i = ail_str_next_unit(s, i); }
        unsigned f = ail__sp(c);
        if (f & 16u) return 0;
        if (f & 64u) cased = 1;
    }
    return cased;
}
static int64_t ail_str_islower(ail_str s) {
    int cased = 0;
    for (int64_t i = 0; i < s.n; ) {
        uint32_t c = s.p[i];
        if (c < 0x80) i++; else { c = ail_str_point(s, i); i = ail_str_next_unit(s, i); }
        unsigned f = ail__sp(c);
        if (f & 32u) return 0;
        if (f & 128u) cased = 1;
    }
    return cased;
}
/* istitle(): an uppercase/titlecase character may only follow an uncased one, a lowercase one
   only a cased one; at least one cased character. */
static int64_t ail_str_istitle(ail_str s) {
    int cased = 0, prev = 0;
    for (int64_t i = 0; i < s.n; ) {
        uint32_t c = s.p[i];
        if (c < 0x80) i++; else { c = ail_str_point(s, i); i = ail_str_next_unit(s, i); }
        unsigned f = ail__sp(c);
        if (f & 32u) { if (prev) return 0; prev = 1; cased = 1; }
        else if (f & 128u) { if (!prev) return 0; prev = 1; cased = 1; }
        else prev = 0;
    }
    return cased;
}
'''
    for key, value in {
        '@PY@': sys.version.split()[0], '@UNI@': unicodedata.unidata_version,
        '@BLOCKS@': str(len(blocks)), '@SIZE@': str(1 << shift), '@TOTAL@': str(total),
        '@ITYPE@': 'uint16_t' if wide else 'uint8_t', '@NIDX@': str(len(index)), '@IDX@': lines(index, 24),
        '@NBLK@': str(len(flat)), '@BLK@': lines(flat, 24), '@SHIFT@': str(shift), '@MASK@': str((1 << shift) - 1),
    }.items():
        section = section.replace(key, value)
    block = BEGIN + "STRPRED = r'''" + section + "'''\n" + END
    text = CRUNTIME.read_text()
    if BEGIN in text:
        start = text.index(BEGIN)
        end = text.index(END) + len(END)
        text = text[:start] + block + text[end:]
    else:
        anchor = '\nORDER = ['
        text = text.replace(anchor, '\n' + block + anchor, 1)
    CRUNTIME.write_text(text)
    print('shift %d, %d blocks, %d bytes of tables, highest flagged code point 0x%X' % (shift, len(blocks), total, limit - 1))


if __name__ == '__main__':
    main()
