"""Generate the general-category ranges for `unicodedata.category()`.

    python3 tools/gen_unicodecat.py

The ranges are derived from the running CPython (3.12: Unicode 15.0): every code point's
`unicodedata.category(chr(cp))` is folded into a sorted list of inclusive ranges. The table is read by
ail_syntax.py and copied into the helper a program that calls `unicodedata.category()` gets, so the
compiled program needs no Python runtime and no Unicode database of its own.
"""
import sys
import unicodedata
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / 'AIL_CURRENT/python/pkg-v12/unicodecat.py'


def ranges():
    out = []
    start = 0
    category = unicodedata.category(chr(0))
    for cp in range(1, 0x110000):
        found = unicodedata.category(chr(cp))
        if found != category:
            out.append((start, cp - 1, category))
            start, category = cp, found
    out.append((start, 0x10FFFF, category))
    return out


def main():
    rows = ranges()
    table = '\n'.join('%06X%06X%s' % row for row in rows)
    text = ('"""Unicode general-category ranges for unicodedata.category(), generated by '
            'tools/gen_unicodecat.py from CPython %s (Unicode %s) -- do not edit by hand.\n\n'
            'Each line is a six-digit inclusive start, a six-digit inclusive end and the two-letter\n'
            'general category, sorted by code point.\n"""\nRANGES = %r\n'
            % (sys.version.split()[0], unicodedata.unidata_version, table))
    TARGET.write_text(text, encoding='utf-8')
    print('%s: %d ranges, %d bytes' % (TARGET, len(rows), len(table)))


if __name__ == '__main__':
    main()
