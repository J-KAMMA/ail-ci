"""Generate the CASEMAP runtime section (full Unicode str.lower()/str.upper()) into cruntime.py.

    python3 tools/gen_casemap.py

Everything is derived from the running CPython (3.12: Unicode 15.0) so the result is CPython's own:
- the lower/upper mapping of every code point whose mapping differs (some map to 2-3 characters);
- for the Final_Sigma rule of str.lower() (U+03A3 becomes U+03C2 at the end of a word), which code
  points are "cased" and which are "case-ignorable", found by asking str.lower() itself:
    A(c) = (c + 'Σ').lower() ends in 'ς'          -> c is cased and not case-ignorable
    B(c) = ('A' + c + 'Σ').lower() ends in 'ς'    -> c is case-ignorable or cased
    C(c) = ('AΣ' + c).lower()[1] == 'ς'           -> c is case-ignorable or not cased
  so case-ignorable = B and C and not A (whether an ignorable character is cased never matters,
  because the rule skips ignorable characters).
The section is written between the BEGIN/END GENERATED CASEMAP markers in cruntime.py, and the
str.casefold() table (the CASEFOLD part, emitted only for a program that calls casefold) right after
it between the BEGIN/END GENERATED CASEFOLD markers.
"""
import sys
from pathlib import Path

CRUNTIME = Path(__file__).resolve().parents[1] / 'AIL_CURRENT/python/pkg-v12/cruntime.py'
BEGIN, END = '# BEGIN GENERATED CASEMAP\n', '# END GENERATED CASEMAP\n'


def code_points():
    for cp in range(0x110000):
        if not 0xD800 <= cp <= 0xDFFF:
            yield cp


def ranges(flags):
    out, start = [], None
    for cp in range(0x110001):
        on = cp < 0x110000 and flags.get(cp, False)
        if on and start is None:
            start = cp
        elif not on and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def table(name, mapping):
    pool, entries = bytearray(), []
    for cp in sorted(mapping):
        data = mapping[cp].encode('utf-8')
        entries.append((cp, len(pool), len(data)))
        pool += data
    lines = ['static const uint32_t ail__%s_cp[%d] = {' % (name, len(entries))]
    lines += ['    ' + ', '.join('0x%X' % e[0] for e in entries[i:i + 12]) + ',' for i in range(0, len(entries), 12)]
    lines.append('};')
    lines.append('static const uint32_t ail__%s_at[%d] = {  /* pool offset << 3 | length */' % (name, len(entries)))
    lines += ['    ' + ', '.join('%d' % (e[1] << 3 | e[2]) for e in entries[i:i + 16]) + ',' for i in range(0, len(entries), 16)]
    lines.append('};')
    chunks = [''.join('\\x%02X' % b for b in pool[i:i + 40]) for i in range(0, len(pool), 40)]
    lines.append('static const uint8_t ail__%s_pool[%d] =' % (name, len(pool) + 1))
    lines += ['    "%s"' % c for c in chunks]
    lines[-1] += ';'
    return '\n'.join(lines), len(entries)


def range_table(name, spans):
    lines = ['static const uint32_t ail__%s[%d][2] = {' % (name, len(spans))]
    lines += ['    ' + ', '.join('{0x%X, 0x%X}' % s for s in spans[i:i + 6]) + ',' for i in range(0, len(spans), 6)]
    lines.append('};')
    return '\n'.join(lines)


def main():
    lower, upper, cased, ignorable = {}, {}, {}, {}
    worst = 1.0
    for cp in code_points():
        c = chr(cp)
        lo, up = c.lower(), c.upper()
        if lo != c:
            lower[cp] = lo
        if up != c:
            upper[cp] = up
        width = len(c.encode('utf-8'))
        worst = max(worst, len(lo.encode('utf-8')) / width, len(up.encode('utf-8')) / width)
        a = (c + 'Σ').lower().endswith('ς')
        b = ('A' + c + 'Σ').lower().endswith('ς')
        cc = ('AΣ' + c).lower()[1] == 'ς'
        if a:
            cased[cp] = True
        if b and cc and not a:
            ignorable[cp] = True
    assert worst <= 3.0, worst
    lower_c, n_lower = table('lower', lower)
    upper_c, n_upper = table('upper', upper)
    section = r'''/* Full Unicode str.lower() / str.upper(), generated by tools/gen_casemap.py from CPython %s
   (Unicode %s) -- do not edit by hand. %d code points change under lower(), %d under upper();
   some map to two or three characters (U+00DF -> "SS"). lower() applies CPython's Final_Sigma rule
   to U+03A3. Output is at most three times the input in UTF-8 bytes. */
%s
%s
%s
%s
static int64_t ail__case_find(const uint32_t *keys, int64_t n, uint32_t cp) {
    int64_t lo = 0, hi = n - 1;
    while (lo <= hi) {
        int64_t mid = (lo + hi) / 2;
        if (keys[mid] == cp) return mid;
        if (keys[mid] < cp) lo = mid + 1; else hi = mid - 1;
    }
    return -1;
}
static int ail__case_in(const uint32_t (*spans)[2], int64_t n, uint32_t cp) {
    int64_t lo = 0, hi = n - 1;
    while (lo <= hi) {
        int64_t mid = (lo + hi) / 2;
        if (cp < spans[mid][0]) hi = mid - 1;
        else if (cp > spans[mid][1]) lo = mid + 1;
        else return 1;
    }
    return 0;
}
#define AIL__CASED(cp) ail__case_in(ail__cased, (int64_t)(sizeof ail__cased / sizeof ail__cased[0]), (cp))
#define AIL__IGNORABLE(cp) ail__case_in(ail__ignorable, (int64_t)(sizeof ail__ignorable / sizeof ail__ignorable[0]), (cp))
/* CPython's handle_capital_sigma: U+03A3 lowers to U+03C2 when a cased character precedes it
   (skipping case-ignorable ones) and no cased character follows it (skipping likewise). */
static int ail__final_sigma(ail_str s, int64_t at) {
    int64_t j = at;
    int found = 0;
    while (j > 0) {
        j = ail_str_prev_unit(s, j);
        uint32_t c = ail_str_point(s, j);
        if (AIL__IGNORABLE(c)) continue;
        found = AIL__CASED(c);
        break;
    }
    if (!found) return 0;
    for (j = ail_str_next_unit(s, at); j < s.n; j = ail_str_next_unit(s, j)) {
        uint32_t c = ail_str_point(s, j);
        if (AIL__IGNORABLE(c)) continue;
        return !AIL__CASED(c);
    }
    return 1;
}
static ail_str ail__case_map(ail_sarena *A, ail_str s, int upper) {
    int ascii = 1;
    for (int64_t i = 0; i < s.n; i++) if (s.p[i] & 0x80) { ascii = 0; break; }
    if (ascii) {
        uint8_t *q = (uint8_t *)ail_alloc(((size_t)s.n + 1) * sizeof(uint8_t));
        for (int64_t i = 0; i < s.n; i++) {
            uint8_t c = s.p[i];
            q[i] = upper ? (uint8_t)(c >= 97 && c <= 122 ? c - 32 : c) : (uint8_t)(c >= 65 && c <= 90 ? c + 32 : c);
        }
        ail_sarena_pushn(A, q, -(s.n + 1));
        ail_str r; r.bytes = 1; r.p = q; r.n = s.n; return r;
    }
    if (s.n > (INT64_MAX - 1) / 3) ail_die("string too long");
    uint8_t *q = (uint8_t *)ail_alloc((size_t)(3 * s.n + 1));
    int64_t o = 0;
    const uint32_t *keys = upper ? ail__upper_cp : ail__lower_cp;
    const uint32_t *at = upper ? ail__upper_at : ail__lower_at;
    const uint8_t *pool = upper ? ail__upper_pool : ail__lower_pool;
    int64_t count = upper ? (int64_t)(sizeof ail__upper_cp / sizeof ail__upper_cp[0])
                          : (int64_t)(sizeof ail__lower_cp / sizeof ail__lower_cp[0]);
    for (int64_t i = 0; i < s.n; ) {
        int64_t next = ail_str_next_unit(s, i);
        uint32_t c = s.p[i] < 0x80 ? s.p[i] : ail_str_point(s, i);
        if (c < 0x80) {
            q[o++] = upper ? (uint8_t)(c >= 97 && c <= 122 ? c - 32 : c) : (uint8_t)(c >= 65 && c <= 90 ? c + 32 : c);
        } else if (!upper && c == 0x3A3) {
            uint32_t sigma = ail__final_sigma(s, i) ? 0x3C2 : 0x3C3;
            q[o++] = (uint8_t)(0xC0 | (sigma >> 6)); q[o++] = (uint8_t)(0x80 | (sigma & 0x3F));
        } else {
            int64_t k = ail__case_find(keys, count, c);
            if (k >= 0) {
                uint32_t len = at[k] & 7, off = at[k] >> 3;
                memcpy(q + o, pool + off, len); o += len;
            } else {
                memcpy(q + o, s.p + i, (size_t)(next - i)); o += next - i;
            }
        }
        i = next;
    }
    ail_sarena_pushn(A, q, -(3 * s.n + 1));
    ail_str r; r.bytes = 0; r.p = q; r.n = o; return r;
}
static ail_str ail_str_lower(ail_sarena *A, ail_str s) { return ail__case_map(A, s, 0); }
static ail_str ail_str_upper(ail_sarena *A, ail_str s) { return ail__case_map(A, s, 1); }
''' % (sys.version.split()[0], __import__('unicodedata').unidata_version, n_lower, n_upper,
       lower_c, upper_c, range_table('cased', ranges(cased)), range_table('ignorable', ranges(ignorable)))
    block = BEGIN + "CASEMAP = r'''" + section + "'''\n" + END
    text = CRUNTIME.read_text()
    if BEGIN in text:
        start = text.index(BEGIN)
        end = text.index(END) + len(END)
        text = text[:start] + block + text[end:]
    else:
        anchor = '\nORDER = ['
        text = text.replace(anchor, '\n' + block + anchor, 1)
    text = text.replace(block, block + casefold_block(lower), 1) if FOLD_BEGIN not in text else text
    if FOLD_BEGIN in text:
        start = text.index(FOLD_BEGIN)
        end = text.index(FOLD_END) + len(FOLD_END)
        text = text[:start] + casefold_block(lower) + text[end:]
    CRUNTIME.write_text(text)
    print('lower %d, upper %d, cased spans %d, ignorable spans %d' % (
        n_lower, n_upper, len(ranges(cased)), len(ranges(ignorable))))


FOLD_BEGIN, FOLD_END = '# BEGIN GENERATED CASEFOLD\n', '# END GENERATED CASEFOLD\n'


def casefold_block(lower):
    """The CASEFOLD part: str.casefold() is the per-character full case folding, which differs
    from the per-character lower() mapping for a few hundred code points (U+00DF -> "ss", U+03C2
    -> U+03C3, ...); those are the table, and every other code point folds as CASEMAP lowers it
    (without the Final_Sigma rule, which casefold does not apply)."""
    fold = {}
    for cp in code_points():
        c = chr(cp)
        if c.casefold() != lower.get(cp, c):
            fold[cp] = c.casefold()
    for cp, text in fold.items():
        assert len(text.encode('utf-8')) <= 3 * len(chr(cp).encode('utf-8'))
    fold_c, n_fold = table('fold', fold)
    section = r'''/* str.casefold(), generated by tools/gen_casemap.py from CPython %s (Unicode %s) -- do not
   edit by hand. %d code points fold differently from their lower() mapping; every other one folds
   as CASEMAP lowers it, with no Final_Sigma rule. Output is at most three times the input. */
%s
static ail_str ail_str_casefold(ail_sarena *A, ail_str s) {
    int ascii = 1;
    for (int64_t i = 0; i < s.n; i++) if (s.p[i] & 0x80) { ascii = 0; break; }
    if (ascii) return ail__case_map(A, s, 0);
    if (s.n > (INT64_MAX - 1) / 3) ail_die("string too long");
    uint8_t *q = (uint8_t *)ail_alloc((size_t)(3 * s.n + 1));
    int64_t o = 0;
    const int64_t nfold = (int64_t)(sizeof ail__fold_cp / sizeof ail__fold_cp[0]);
    const int64_t nlower = (int64_t)(sizeof ail__lower_cp / sizeof ail__lower_cp[0]);
    for (int64_t i = 0; i < s.n; ) {
        int64_t next = ail_str_next_unit(s, i);
        uint32_t c = s.p[i] < 0x80 ? s.p[i] : ail_str_point(s, i);
        int64_t k;
        if (c < 0x80) {
            q[o++] = (uint8_t)(c >= 65 && c <= 90 ? c + 32 : c);
        } else if ((k = ail__case_find(ail__fold_cp, nfold, c)) >= 0) {
            uint32_t len = ail__fold_at[k] & 7, off = ail__fold_at[k] >> 3;
            memcpy(q + o, ail__fold_pool + off, len); o += len;
        } else if ((k = ail__case_find(ail__lower_cp, nlower, c)) >= 0) {
            uint32_t len = ail__lower_at[k] & 7, off = ail__lower_at[k] >> 3;
            memcpy(q + o, ail__lower_pool + off, len); o += len;
        } else {
            memcpy(q + o, s.p + i, (size_t)(next - i)); o += next - i;
        }
        i = next;
    }
    ail_sarena_pushn(A, q, -(3 * s.n + 1));
    ail_str r; r.bytes = 0; r.p = q; r.n = o; return r;
}
''' % (sys.version.split()[0], __import__('unicodedata').unidata_version, n_fold, fold_c)
    return FOLD_BEGIN + "CASEFOLD = r'''" + section + "'''\n" + FOLD_END


if __name__ == '__main__':
    main()
