"""Generate AIL_CURRENT/stdlib/unicodedata.py from the running CPython's Unicode database.

    python3 tools/gen_unicodedata.py

The module is the AIL standard-library `unicodedata` (found in the bundled `stdlib/` last, like
`zlib`): it builds `category(ch)` exactly as CPython 3.12's unicodedata.category does, for every code
point AIL's 16-bit strings can hold. The data is the General_Category of each code point in a run-length
table (one start and one category code per run, 4007 runs for Unicode 15.0); the module binary-searches
the starts. Surrogate code points are `Cs`; `name`, `normalize` and the rest of the module are not built
and the compiler refuses them by name.
"""
import sys
import unicodedata
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / 'AIL_CURRENT' / 'stdlib' / 'unicodedata.py'


def runs():
    out = []
    for cp in range(0x110000):
        cat = 'Cs' if 0xD800 <= cp <= 0xDFFF else unicodedata.category(chr(cp))
        if not out or out[-1][1] != cat:
            out.append((cp, cat))
    return out


def list_literal(values, per=20):
    return '\n'.join('    ' + ', '.join(str(value) for value in values[i:i + per]) + ','
                     for i in range(0, len(values), per))


def string_literal(text, per=90):
    lines = []
    for i in range(0, len(text), per):
        chunk = text[i:i + per]
        escaped = ''.join(ch if 32 <= ord(ch) < 127 and ch not in '\\\'"' else '\\x%02X' % ord(ch)
                          for ch in chunk)
        lines.append("    '%s'" % escaped)
    return '\n'.join(lines)


def main():
    table = runs()
    categories = sorted({cat for _, cat in table})
    index = {cat: number for number, cat in enumerate(categories)}
    starts = [cp for cp, _ in table]
    codes = ''.join(chr(48 + index[cat]) for _, cat in table)
    text = '''"""The stdlib `unicodedata` module for AIL: `category()` only, from CPython's Unicode %(unicode)s data.

Generated by tools/gen_unicodedata.py. `category(ch)` returns the General_Category of a one-character
string exactly as CPython 3.12's unicodedata.category does, for every code point AIL's 16-bit strings can
hold. `name()`, `normalize()`, `lookup()`, `decimal()`, `digit()`, `numeric()`, `bidirectional()`,
`combining()`, `east_asian_width()`, `mirrored()`, `decomposition()` and the constants are not built:
the compiler refuses them by name (no such name in the module).
"""
_CATEGORIES = (%(categories)s)
_STARTS = [
%(starts)s
]
_CODES = (
%(codes)s
)


def category(ch: str) -> str:
    if not isinstance(ch, str):
        name = "None"
        if ch is not None:
            name = type(ch).__name__
        raise TypeError("category() argument must be a unicode character, not " + name)
    if len(ch) != 1:
        raise TypeError("category() argument must be a unicode character, not str")
    cp = ord(ch)
    lo = 0
    hi = len(_STARTS) - 1
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if _STARTS[mid] <= cp:
            lo = mid
        else:
            hi = mid - 1
    return _CATEGORIES[ord(_CODES[lo]) - 48]
''' % {
        'unicode': unicodedata.unidata_version,
        'categories': ', '.join("'%s'" % cat for cat in categories),
        'starts': list_literal(starts),
        'codes': string_literal(codes),
    }
    TARGET.write_text(text, encoding='utf-8')
    print('%s: %d runs, %d categories, %d bytes (Unicode %s, Python %d.%d)' % (
        TARGET.relative_to(TARGET.parents[2]), len(table), len(categories), len(text),
        unicodedata.unidata_version, *sys.version_info[:2]))


if __name__ == '__main__':
    main()
