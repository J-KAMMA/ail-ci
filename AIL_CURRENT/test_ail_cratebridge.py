    @unittest.skipUnless(RUSTC, "rustc required")
    def test_rust_crate_cdylib_and_staticlib(self):
        rdir = self.dir / "rust"
        rdir.mkdir()
        (rdir / "tinyrs.rs").write_text(RS_SOURCE, encoding="utf8")
        (rdir / "tinyrs.h").write_text(RS_HEADER, encoding="utf8")
        shutil.copyfile(ROOT / "ail_cbuf.py", rdir / "ail_cbuf.py")
        for kind, name in (("cdylib", "libtinyrs.so"), ("staticlib", "libtinyrs.a")):
            done = subprocess.run([RUSTC, "--edition", "2021", "--crate-type", kind, "--crate-name", "tinyrs", "-C", "opt-level=1",
                                   "-C", "panic=abort", "-o", str(rdir / name), str(rdir / "tinyrs.rs")],
                                  capture_output=True, text=True, timeout=600)
            self.assertEqual(done.returncode, 0, done.stderr)
        check = "rs_checked_div=nonzero:ValueError"
        done = subprocess.run([sys.executable, str(BINDGEN), str(rdir / "tinyrs.h"), "--lib", "./libtinyrs.so", "--check", check,
                               "--check", "rs_greet=negative:ValueError"], capture_output=True, text=True)
        self.assertEqual(done.returncode, 0, done.stderr)
        stubs = done.stdout
        self.assertIn("def rs_sum_f64(xs: cptr(c_double), n: length('xs'))", stubs)
        self.assertIn("def rs_greet(name: c_char_p, out: bytearray, cap: length('out')) -> c_ssize_t", stubs)
        self.assertIn("def rs_counter_new(start: c_int32) -> c_void_p", stubs)
        # the generated stubs call rs_sum_f64 with the length supplied; the program passes a bytes of doubles
        program = RS_MAIN.replace("{STUBS}", stubs)
        cpy = (rdir / "rs_cpy.py")
        cpy.write_text(program.replace("{MSG}", "str(e)"), encoding="utf8")
        expected = run_cpython(rdir, "rs_cpy.py")
        self.assertEqual(expected.returncode, 0, expected.stderr)
        (rdir / "rs_ail.py").write_text(program.replace("{MSG}", "e.message"), encoding="utf8")
        built, exe = compile_cli(rdir, "rs_ail.py", name="rs_so.out")
        self.assertEqual(built.returncode, 0, built.stderr)
        ran = subprocess.run([str(exe)], cwd=rdir, capture_output=True, text=True, timeout=60)
        self.assertEqual(ran.returncode, 0, ran.stderr)
        self.assertEqual(expected.stdout, ran.stdout)
        self.assertIn("greet rs_greet failed with -1", ran.stdout)
        self.assertIn("hello, wörld!", ran.stdout)
        self.assertIn("div rs_checked_div failed with 1", ran.stdout)
        # the same program linked to the static library: only the compiled side can use a .a
        (rdir / "rs_static.py").write_text(program.replace("{MSG}", "e.message").replace("./libtinyrs.so", "./libtinyrs.a"),
                                           encoding="utf8")
        built, exe = compile_cli(rdir, "rs_static.py", name="rs_a.out")
        self.assertEqual(built.returncode, 0, built.stderr)
        ran_a = subprocess.run([str(exe)], cwd=rdir, capture_output=True, text=True, timeout=60)
        self.assertEqual(ran_a.returncode, 0, ran_a.stderr)
        self.assertEqual(ran_a.stdout, expected.stdout)


