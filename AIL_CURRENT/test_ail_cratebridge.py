"""Cratebridge: using existing native libraries from AIL (G4 follow-up).

* `link("m", "z", "sqlite3")` at module level names the system libraries a file's stubs resolve in. The compiled
  program links `-lm -lz -lsqlite3`; the CPython shim loads the same libraries by name.
* A struct passed by pointer is a bytearray read and written with `ail_cbuf` (offsets by hand): `gmtime_r`.
* `ptr(c_void_p)` is the `void **` out-parameter that returns a handle: `sqlite3_open`.
* A Rust crate that exports `extern "C"` functions (cdylib, or staticlib on the compiled side) is called the same
  way; the stubs are generated by `ail_bindgen.py` from a cbindgen-style header. Skipped when rustc is missing.

Every program runs twice and the outputs must be equal: `python3 prog.py` (ail_ffi's ctypes shim) and the
executable `ail_chatgpt.py compile prog.py` builds (typed path, AIL_NO_GENERAL=1).
"""
