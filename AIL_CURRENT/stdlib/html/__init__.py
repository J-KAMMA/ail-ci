__all__ = ['escape', 'unescape']


def escape(s: str, quote=True) -> str:
    """Replace special characters "&", "<" and ">" to HTML-safe sequences."""
    out = s.replace("&", "&amp;")
    out = out.replace("<", "&lt;")
    out = out.replace(">", "&gt;")
    if quote:
        out = out.replace('"', "&quot;")
        out = out.replace("'", "&#x27;")
    return out


