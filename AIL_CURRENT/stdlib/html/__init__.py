def _named_ref(s: str) -> str:
    if s in _html5:
        return _html5[s]
    for i in range(len(_astral_names)):
        if _astral_names[i] == s:
            return chr(_astral_codes[i])
    return ''


def _replace_charref(s: str) -> str:
    if s[0] == '#':
        if s[1] in 'xX':
            digits = s[2:].rstrip(';')
            while len(digits) > 1 and digits[0] == '0':
                digits = digits[1:]
            if len(digits) > 6:
                return '\uFFFD'
            num = int(digits, 16)
        else:
            digits = s[1:].rstrip(';')
            while len(digits) > 1 and digits[0] == '0':
                digits = digits[1:]
            if len(digits) > 7:
                return '\uFFFD'
            num = int(digits)
        if num in _invalid_charrefs:
            return _invalid_charrefs[num]
        if 0xD800 <= num and num <= 0xDFFF or num > 0x10FFFF:
            return '\uFFFD'
        if num in _invalid_codepoints:
            return ''
        return chr(num)
    value = _named_ref(s)
    if value != '':
        return value
    for x in range(len(s) - 1, 1, -1):
        value = _named_ref(s[:x])
        if value != '':
            return value + s[x:]
    return '&' + s


def _charref_end(s: str, start: int) -> int:
    """The end of the character reference at `start` (an '&'), or -1.

    This is CPython's _charref regular expression written as a scan loop: `&#[0-9]+;?`,
    `&#[xX][0-9a-fA-F]+;?`, or 1..32 characters that are not tab, newline, form feed,
    space, <, &, # or ;, with an optional ;.
    """
    n = len(s)
    i = start + 1
    if i < n and s[i] == '#':
        j = i + 1
        if j < n and s[j] in 'xX':
            k = j + 1
            while k < n and s[k] in '0123456789abcdefABCDEF':
                k = k + 1
            if k == j + 1:
                return -1
            if k < n and s[k] == ';':
                k = k + 1
            return k
        k = j
        while k < n and '0' <= s[k] and s[k] <= '9':
            k = k + 1
        if k == j:
            return -1
        if k < n and s[k] == ';':
            k = k + 1
        return k
    k = i
    limit = i + 32
    while k < n and k < limit and s[k] not in '\t\n\f <&#;':
        k = k + 1
    if k == i:
        return -1
    if k < n and s[k] == ';':
        k = k + 1
    return k


def unescape(s: str) -> str:
    """Convert all named and numeric character references in the string s.

    CPython writes this as `_charref.sub(_replace_charref, s)`.  The compiler refuses
    re.sub with a function, so the same regular expression is written as the scan loop
    below; the result is identical.
    """
    if '&' not in s:
        return s
    out = []
    i = 0
    n = len(s)
    while i < n:
        if s[i] != '&':
            j = i
            while j < n and s[j] != '&':
                j = j + 1
            out.append(s[i:j])
            i = j
            continue
        end = _charref_end(s, i)
        if end < 0:
            out.append('&')
            i = i + 1
            continue
        out.append(_replace_charref(s[i + 1:end]))
        i = end
    return ''.join(out)