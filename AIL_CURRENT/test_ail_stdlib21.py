"""Library batch 21: `unicodedata.category` and `textwrap.shorten`, compared with CPython 3.12 on both builds.

`unicodedata` was the most-imported module the corpus still refused outright (three programs). The
bundled `stdlib/unicodedata.py` is generated by `tools/gen_unicodedata.py` from CPython's Unicode 15.0
General_Category data (one start and one category code per run, 4007 runs) and builds `category(ch)`
exactly as CPython does, including `TypeError` for an empty or longer string and for a non-str value.
`name`, `normalize` and every other name stay a named compile-time refusal: the bundled module has no
such name, so the compiler reports it.

The next still-refused corpus use is `textwrap.shorten` (one program; the module was otherwise built).
It is lowered to `_ail_tw_shorten`, which runs CPython's default TextWrapper with `max_lines=1`: it
collapses whitespace, uses the same hyphen / em-dash chunks and `_handle_long_word`, and appends the
default `" [...]"` placeholder exactly as CPython 3.12 does for every width. The `placeholder=` keyword
and the other TextWrapper options stay a named compile-time refusal; the width is required, as in
CPython 3.12.

Every program below is ordinary Python. CPython runs it as the oracle; the compiled program (AIL_IR=0
and AIL_IR=1) prints the same bytes, or the spelling is refused by name.
"""
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def compile_python(directory, text, name, ir):
    source, exe = Path(directory, name + ".ail"), Path(directory, name)
    source.write_text(text, encoding="utf-8")
    env = dict(os.environ, AIL_IR="1" if ir else "0")
    built = subprocess.run([sys.executable, "-B", str(ROOT / "ail_chatgpt.py"), "compile", source.name,
                            "--syntax", "python", "-o", exe.name], cwd=directory, capture_output=True,
                           text=True, timeout=900, env=env)
    oracle = Path(directory, name + "_oracle.py")
    oracle.write_text(text, encoding="utf-8")
    return built, source, exe, oracle


BMP = r"""import sys
import unicodedata


def main() -> None:
    for line in sys.stdin:
        n = int(line)
        if 0xD800 <= n <= 0xDFFF:
            continue
        print(n, unicodedata.category(chr(n)))


main()
"""

ROUTES = r"""import sys
import unicodedata
from unicodedata import category as direct
import unicodedata as ud


class Box:
    def __init__(self, ch: str) -> None:
        self.ch = ch


def via(ch: str) -> str:
    return unicodedata.category(ch)


def main() -> None:
    text = sys.stdin.read()
    if text == "":
        text = "A1 \u00e9\u4e2d\u0301\u200bZ"
    xs = list(text)
    d: dict[str, str] = {}
    i = 0
    while i < len(xs):
        d[str(i)] = xs[i]
        i += 1
    b = Box(xs[0])
    print(via(xs[0]), direct(xs[1]), ud.category(xs[2]), unicodedata.category(b.ch), unicodedata.category(d["0"]))
    for ch in xs:
        print(repr(ch), unicodedata.category(ch))
    for bad in ("", "ab", "\u00e9\u00e9"):
        try:
            print(unicodedata.category(bad))
        except TypeError as e:
            print("TypeError", e)
    for bad in (65, b"a", None, 3.5, [1]):
        try:
            print(unicodedata.category(bad))
        except TypeError as e:
            print("TypeError", e)


main()
"""


SHORTEN = r"""import textwrap
from textwrap import shorten
import textwrap as tw


class Box:
    def __init__(self, text: str) -> None:
        self.text = text


def via(text: str, width: int) -> str:
    return textwrap.shorten(text, width=width)


def show(text: str, width: int) -> None:
    try:
        print(width, repr(textwrap.shorten(text, width)))
    except Exception as e:
        print(width, type(e).__name__, str(e))


def main() -> None:
    texts = ["", "   ", "a", "ab", "hello world", "one two three", "abcdefghij",
             "a-b-c-d-e", "abc-def-ghi", "foo--bar baz", "ab cd", "--foo bar",
             "a\tb\tc", "a\nb\nc", "a\r\nb", "a\x0bb\x0cc", "  a   b  ",
             "a\u00a0b", "a\u2003b", "word-of-two other", "x---y", "co-operate",
             "The quick brown fox jumps over the lazy dog and keeps running"]
    for text in texts:
        for width in (-3, 0, 1, 4, 5, 6, 9, 10, 11, 12, 13, 20, 40, 70):
            show(text, width)
    xs = ["one two three", "hello world", "The quick brown fox jumps over the lazy dog"]
    d: dict[str, str] = {"k": "the quick brown fox jumps over the lazy dog"}
    b = Box("a-b-c-d-e")
    print(via(xs[0], 9))
    print(textwrap.shorten(xs[1], 11), shorten(d["k"], 12), tw.shorten(b.text, 6))
    print(via(d["k"], 20))
    print(textwrap.shorten(xs[2], width=70))
    for text in xs:
        print(shorten(text, 8))
    try:
        print(textwrap.shorten(123, 10))
    except Exception as e:
        print(type(e).__name__, str(e))
    try:
        print(textwrap.shorten(b"one two three", 10))
    except Exception as e:
        print(type(e).__name__, str(e))
    print(textwrap.shorten(xs[1], 10.0))


main()
"""


SHORTEN_FUZZ = r"""import textwrap

ALPHA = "ab AB- .!?&,0123\t\n\r"


def main() -> None:
    state = 123456789
    trial = 0
    while trial < 500:
        state = (state * 1103515245 + 12345) % 2147483648
        length = state % 28
        text = ""
        i = 0
        while i < length:
            state = (state * 1103515245 + 12345) % 2147483648
            text += ALPHA[state % len(ALPHA)]
            i += 1
        state = (state * 1103515245 + 12345) % 2147483648
        width = state % 27
        try:
            print(trial, repr(text), width, repr(textwrap.shorten(text, width)))
        except Exception as e:
            print(trial, repr(text), width, type(e).__name__, str(e))
        trial += 1


main()
"""


class Stdlib21Tests(unittest.TestCase):
    def build(self, directory, text, name, ir):
        built, source, exe, oracle = compile_python(directory, text, name, ir)
        self.assertEqual(built.returncode, 0, "%s (AIL_IR=%d)\n%s%s" % (name, ir, built.stdout, built.stderr))
        return exe, oracle

    def test_every_bmp_category_matches_cpython(self):
        data = "".join("%d\n" % cp for cp in range(0x10000) if not 0xD800 <= cp <= 0xDFFF).encode()
        with tempfile.TemporaryDirectory() as directory:
            Path(directory, "oracle.py").write_text(BMP, encoding="utf-8")
            expected = subprocess.run([sys.executable, str(Path(directory, "oracle.py"))], input=data,
                                      capture_output=True, timeout=300)
            self.assertEqual(expected.returncode, 0, expected.stderr)
            self.assertGreater(len(expected.stdout.splitlines()), 63000)
            for ir in (False, True):
                with self.subTest(ir=ir):
                    exe, _ = self.build(directory, BMP, "bmp_%d" % ir, ir)
                    ran = subprocess.run([str(exe)], input=data, capture_output=True, timeout=300)
                    self.assertEqual((ran.returncode, ran.stdout), (0, expected.stdout), ran.stderr[-500:])

    def test_routes_and_errors_match_cpython(self):
        inputs = [b"", "A1 \u00e9\u4e2d\u0301\u200bZ\n".encode(),
                  " \t\n!?9\u0300\u2028\u3000\u20ac\ud7ff\ue000\n".encode()]
        with tempfile.TemporaryDirectory() as directory:
            for ir in (False, True):
                with self.subTest(ir=ir):
                    exe, oracle = self.build(directory, ROUTES, "routes_%d" % ir, ir)
                    for data in inputs:
                        ran = subprocess.run([str(exe)], input=data, capture_output=True, timeout=300)
                        expected = subprocess.run([sys.executable, str(oracle)], input=data,
                                                  capture_output=True, timeout=300)
                        self.assertEqual(expected.returncode, 0, expected.stderr)
                        self.assertEqual((ran.returncode, ran.stdout), (0, expected.stdout),
                                         ran.stderr[-500:])

    def test_textwrap_shorten_matches_cpython(self):
        for ir in (False, True):
            with self.subTest(ir=ir), tempfile.TemporaryDirectory() as directory:
                exe, oracle = self.build(directory, SHORTEN, "shorten_%d" % ir, ir)
                ran = subprocess.run([str(exe)], capture_output=True, timeout=300)
                expected = subprocess.run([sys.executable, str(oracle)], capture_output=True, timeout=300)
                self.assertEqual(expected.returncode, 0, expected.stderr)
                self.assertEqual((ran.returncode, ran.stdout), (0, expected.stdout), ran.stderr[-500:])

    def test_textwrap_shorten_generated_cases_match_cpython(self):
        for ir in (False, True):
            with self.subTest(ir=ir), tempfile.TemporaryDirectory() as directory:
                exe, oracle = self.build(directory, SHORTEN_FUZZ, "shorten_fuzz_%d" % ir, ir)
                ran = subprocess.run([str(exe)], capture_output=True, timeout=300)
                expected = subprocess.run([sys.executable, str(oracle)], capture_output=True, timeout=300)
                self.assertEqual(expected.returncode, 0, expected.stderr)
                self.assertEqual((ran.returncode, ran.stdout), (0, expected.stdout), ran.stderr[-500:])

    def test_unsupported_names_are_refused(self):
        programs = {
            "name": ("import unicodedata\n\nprint(unicodedata.name('A'))\n", "has no top-level name 'name'"),
            "normalize": ("from unicodedata import normalize\n\nprint(normalize('NFC', 'e'))\n",
                          "has no top-level name 'normalize'"),
            "shorten_width": ("import textwrap\n\nprint(textwrap.shorten('one two three'))\n",
                              "shorten() with these arguments is not built"),
            "shorten_placeholder": (
                "import textwrap\n\nprint(textwrap.shorten('one two three', 10, placeholder='...'))\n",
                "shorten with a placeholder"),
        }
        for key, (text, wanted) in programs.items():
            for ir in (False, True):
                with self.subTest(key=key, ir=ir), tempfile.TemporaryDirectory() as directory:
                    built, _, exe, _ = compile_python(directory, text, "refuse_" + key, ir)
                    self.assertNotEqual(built.returncode, 0, built.stdout + built.stderr)
                    self.assertIn(wanted, built.stdout + built.stderr)
                    self.assertFalse(exe.exists())


if __name__ == "__main__":
    unittest.main()
