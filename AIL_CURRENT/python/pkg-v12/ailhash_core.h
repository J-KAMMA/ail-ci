    __m128i abcd = _mm_shuffle_epi32(_mm_loadu_si128((const __m128i *)st), 0x1B);
    __m128i e0 = _mm_set_epi32((int)st[4], 0, 0, 0);
    for (; nb; nb--, p += 64) {
        __m128i abcd_save = abcd, e0_save = e0, eprev = e0, m[4];
        for (int i = 0; i < 4; i++) m[i] = _mm_shuffle_epi8(_mm_loadu_si128((const __m128i *)(p + 16 * i)), mask);
        AILHS_SHA1_GROUP(0, 0); AILHS_SHA1_GROUP(1, 0); AILHS_SHA1_GROUP(2, 0); AILHS_SHA1_GROUP(3, 0); AILHS_SHA1_GROUP(4, 0);
        AILHS_SHA1_GROUP(5, 1); AILHS_SHA1_GROUP(6, 1); AILHS_SHA1_GROUP(7, 1); AILHS_SHA1_GROUP(8, 1); AILHS_SHA1_GROUP(9, 1);
        AILHS_SHA1_GROUP(10, 2); AILHS_SHA1_GROUP(11, 2); AILHS_SHA1_GROUP(12, 2); AILHS_SHA1_GROUP(13, 2); AILHS_SHA1_GROUP(14, 2);
        AILHS_SHA1_GROUP(15, 3); AILHS_SHA1_GROUP(16, 3); AILHS_SHA1_GROUP(17, 3); AILHS_SHA1_GROUP(18, 3); AILHS_SHA1_GROUP(19, 3);
        e0 = _mm_sha1nexte_epu32(eprev, e0_save);
        abcd = _mm_add_epi32(abcd, abcd_save);
    }
    abcd = _mm_shuffle_epi32(abcd, 0x1B);
