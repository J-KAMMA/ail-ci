def compile_python(directory, text, name, **env):
    source, exe = Path(directory, name + ".ail"), Path(directory, name)
    source.write_text(text, encoding="utf-8")
    built = subprocess.run([sys.executable, "-B", str(ROOT / "ail_chatgpt.py"), "compile", source.name,
                            "--syntax", "python", "-o", exe.name], cwd=directory, capture_output=True,
                           text=True, timeout=900, env=dict(os.environ, **env))
    return built, source, exe


class CompiledPrograms(unittest.TestCase):
    def check(self, name, text, data, ir):
        with tempfile.TemporaryDirectory() as directory:
            env = {"AIL_IR": "1" if ir else "0"}
            built, source, exe = compile_python(directory, text, name, **env)
            self.assertEqual(built.returncode, 0, "%s (AIL_IR=%s)\n%s%s" % (name, env["AIL_IR"], built.stdout, built.stderr))
            Path(directory, "oracle.py").write_text(text, encoding="utf-8")
            want = subprocess.run([sys.executable, "-X", "utf8", str(Path(directory, "oracle.py"))], input=data.encode(),
                                  capture_output=True, timeout=300)
            got = subprocess.run([str(exe)], input=data.encode(), capture_output=True, timeout=300)
            self.assertEqual(got.returncode, want.returncode, "%s (AIL_IR=%s): %s" % (name, env["AIL_IR"], got.stderr[-300:]))
            self.assertEqual(got.stdout, want.stdout, "%s (AIL_IR=%s)" % (name, env["AIL_IR"]))

    def test_category_matches_cpython(self):
        data = "".join("%d\n" % n for n in CODEPOINTS)
        for ir in (False, True):
            with self.subTest(ir=ir):
                self.check("category", PROGRAM, data, ir)

    def test_type_errors_match_cpython(self):
        for ir in (False, True):
            with self.subTest(ir=ir):
                self.check("category_errors", ERRORS, "", ir)


class Refusals(unittest.TestCase):
    def refused(self, text, wanted):
        with tempfile.TemporaryDirectory() as directory:
            built, _, exe = compile_python(directory, text, "refused")
            self.assertNotEqual(built.returncode, 0, "compiled but should be refused: " + wanted)
            self.assertIn(wanted, built.stdout + built.stderr)
            self.assertFalse(exe.exists())

    def test_refusals_name_the_use(self):
        cases = {
            "name": ("import unicodedata\n\nprint(unicodedata.name('A'))\n", "unicodedata.name"),
            "normalize": ("import unicodedata\n\nprint(unicodedata.normalize('NFC', 'e'))\n", "unicodedata.normalize"),
            "two_args": ("import unicodedata\n\nprint(unicodedata.category('a', 'b'))\n",
                         "unicodedata.category() with these arguments"),
            "keyword": ("import unicodedata\n\nprint(unicodedata.category(ch='a'))\n",
                        "unicodedata.category() with these arguments"),
            "value": ("import unicodedata\n\nf = unicodedata.category\nprint(f('a'))\n",
                      "unicodedata.category used as a value"),
            "from_name": ("from unicodedata import name\n\nprint(name('A'))\n", "unicodedata.name"),
        }
        for name, (text, wanted) in cases.items():
            with self.subTest(name):
                self.refused(text, wanted)


