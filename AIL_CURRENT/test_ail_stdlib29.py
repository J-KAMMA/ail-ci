"""Library batch 29: `unicodedata.category()`, lowered onto a generated general-category table.

The program below is ordinary Python. CPython 3.12 is the oracle: the compiled program (the Python
syntax, both AIL_IR builds) prints the same bytes, or the spelling is refused by name at compile time.
The table is generated by tools/gen_unicodecat.py from CPython's own `unicodedata.category` and copied
into the helper, so the executable needs no Python runtime and no Unicode database of its own.

* category: one BMP character through `import unicodedata`, an alias, a from-import, a function
  argument, a list item, a dict value, an instance attribute, a reassigned local, and `chr(n)`.
* the runtime TypeError for empty and longer strings and for non-str values is CPython's message.
* name(), normalize(), more than one argument, keyword arguments and a category value that is read
  (not called) stay named compile-time refusals.
"""
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent

PROGRAM = '''import sys
import unicodedata
import unicodedata as ud
from unicodedata import category as cat


class Holder:
    def __init__(self, ch: str):
        self.ch = ch


def label(ch: str) -> str:
    return unicodedata.category(ch)


def main() -> None:
    for line in sys.stdin:
        n = int(line)
        ch = chr(n)
        a = [ch]
        d = {"k": ch}
        h = Holder(ch)
        x = "a"
        x = ch
        print(n, unicodedata.category(ch), ud.category(ch), cat(ch), label(ch))
        print(unicodedata.category(a[0]), unicodedata.category(d["k"]), unicodedata.category(h.ch), unicodedata.category(x))
        print(unicodedata.category(chr(n)))


main()
'''

ERRORS = '''import unicodedata


def main() -> None:
    for value in ["", "ab", None, 1, 1.5, b"a"]:
        try:
            print(unicodedata.category(value))
        except TypeError as e:
            print("TypeError", e)


main()
'''

